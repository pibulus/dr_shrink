const count = Math.max(1, parseInt(process.argv[2], 10) || 5);

function pick(arr) {
  return arr[crypto.randomInt(arr.length)];
}

console.log(
  "// Paste these hashes into VALID_CODE_HASHES in supporterService.js:\n",
);

for (let i = 0; i < count; i++) {
  const phrase = [pick(WORDS), pick(WORDS), pick(WORDS), pick(WORDS)];
  const code = `DS-${phrase.join("-")}`.toUpperCase();

  const hash = crypto.createHash("sha256").update(code).digest("hex");

  console.log(`  "${hash}", // ${code}`);
}

console.log(
  `\n// ${count} code${count > 1 ? "s" : ""} generated. Codes above — give these to contributors.`,
);
